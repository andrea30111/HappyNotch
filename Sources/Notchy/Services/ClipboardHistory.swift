import AppKit
import Combine
import CryptoKit

struct ClipboardItem: Identifiable, Codable, Hashable {
    enum Kind: String, Codable, CaseIterable {
        case text, link, image, file
    }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var sourceApp: String?
    var createdAt = Date()
    var isPinned = false
    var signature: String
}

/// Keeps the most recent copies from the system pasteboard, stored only on this Mac.
/// The pasteboard has no change notification, so this checks `changeCount` (a cheap integer read) twice a second.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let limit = 100
    static let maxTextLength = 100_000
    static let maxImageBytes = 25 * 1024 * 1024

    @Published private(set) var items: [ClipboardItem] = []

    private let store: Store
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?
    private var cancellables = Set<AnyCancellable>()

    /// Types set by password managers and other apps that ask not to be recorded (nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    nonisolated static var fileURL: URL { Store.supportDirectory.appendingPathComponent("clipboard.json") }

    nonisolated static var imagesDirectory: URL {
        let dir = Store.supportDirectory.appendingPathComponent("Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    init(store: Store) {
        self.store = store
        load()
        store.$settings
            .map(\.clipboardHistoryEnabled)
            .removeDuplicates()
            .sink { [weak self] enabled in
                if enabled { self?.start() } else { self?.stop() }
            }
            .store(in: &cancellables)
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        item.imageFile.map { Self.imagesDirectory.appendingPathComponent($0) }
    }

    // MARK: Monitoring

    private func start() {
        lastChangeCount = NSPasteboard.general.changeCount
        timer?.invalidate()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        if let item = capture(from: pasteboard) { insert(item) }
    }

    private func capture(from pasteboard: NSPasteboard) -> ClipboardItem? {
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return nil }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return ClipboardItem(kind: .file, text: paths, sourceApp: source, signature: "file:" + paths)
        }

        if let string = pasteboard.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            let text = String(string.prefix(Self.maxTextLength))
            if let url = URL(string: trimmed), let scheme = url.scheme, ["http", "https"].contains(scheme.lowercased()),
               !trimmed.contains(where: \.isWhitespace) {
                return ClipboardItem(kind: .link, text: trimmed, sourceApp: source, signature: "link:" + trimmed)
            }
            return ClipboardItem(kind: .text, text: text, sourceApp: source, signature: "text:" + Self.hash(Data(text.utf8)))
        }

        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= Self.maxImageBytes {
            let png = pasteboard.data(forType: .png) ?? NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            guard let png else { return nil }
            let signature = "image:" + Self.hash(png)
            if let existing = items.first(where: { $0.signature == signature }) { return existing }
            let fileName = "\(UUID().uuidString).png"
            do {
                try png.write(to: Self.imagesDirectory.appendingPathComponent(fileName), options: .atomic)
            } catch {
                return nil
            }
            return ClipboardItem(kind: .image, imageFile: fileName, sourceApp: source, signature: signature)
        }
        return nil
    }

    private func insert(_ item: ClipboardItem) {
        var new = item
        if let index = items.firstIndex(where: { $0.signature == item.signature }) {
            new = items.remove(at: index)
            new.createdAt = Date()
            new.sourceApp = item.sourceApp ?? new.sourceApp
        }
        items.insert(new, at: 0)
        trim()
        scheduleSave()
    }

    /// Evicts the oldest unpinned items beyond the limit.
    private func trim() {
        while items.count > Self.limit, let index = items.lastIndex(where: { !$0.isPinned }) {
            removeFiles(of: items.remove(at: index))
        }
    }

    // MARK: Actions

    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .file:
            let urls = (item.text ?? "").split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            pasteboard.writeObjects(urls)
        case .image:
            if let url = imageURL(for: item), let image = NSImage(contentsOf: url) {
                pasteboard.writeObjects([image])
            }
        }
        lastChangeCount = pasteboard.changeCount
        if let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.createdAt = Date()
            items.insert(moved, at: 0)
            scheduleSave()
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        trim()
        scheduleSave()
    }

    func delete(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        removeFiles(of: items.remove(at: index))
        scheduleSave()
    }

    func clear(keepPinned: Bool = true) {
        let removed = items.filter { !keepPinned || !$0.isPinned }
        removed.forEach(removeFiles)
        items.removeAll { !keepPinned || !$0.isPinned }
        scheduleSave()
    }

    private func removeFiles(of item: ClipboardItem) {
        guard let url = imageURL(for: item) else { return }
        try? FileManager.default.removeItem(at: url)
        Thumbnailer.cache.removeObject(forKey: url as NSURL)
    }

    // MARK: Persistence

    private func load() {
        guard let data = try? Data(contentsOf: Self.fileURL),
              let decoded = try? Store.makeDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = decoded
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.saveNow() }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    func saveNow() {
        saveWork?.cancel()
        guard let data = try? Store.makeEncoder().encode(items) else { return }
        try? data.write(to: Self.fileURL, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: Self.fileURL.path)
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
    }
}
